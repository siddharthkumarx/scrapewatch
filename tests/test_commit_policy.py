import importlib.util
import pathlib

_spec = importlib.util.spec_from_file_location(
    "commit_policy", pathlib.Path(__file__).resolve().parents[1] / "scripts" / "commit_policy.py"
)
assert _spec is not None
assert _spec.loader is not None
commit_policy = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(commit_policy)
problems = commit_policy.problems


def test_plain_message_passes() -> None:
    assert problems("guard: add consent-wall rule\n\nAdds a generic rule.\n") == []


def test_signed_off_by_is_allowed() -> None:
    msg = "cost: price retries\n\nSigned-off-by: Example Person <person@example.com>\n"
    assert problems(msg) == []


def test_other_trailers_are_rejected() -> None:
    msg = (
        "cost: price retries\n\n"
        "Co-authored-by: Another Person <another@example.com>\n"
        "Reviewed-by: Someone Else <else@example.com>\n"
    )
    probs = problems(msg)
    assert any("Co-authored-by" in p for p in probs)
    assert any("Reviewed-by" in p for p in probs)


def test_generated_footer_is_rejected() -> None:
    assert problems("docs: tidy\n\nGenerated with SomeTool\n")
    assert problems("docs: tidy\n\nThis commit was generated by a script.\n")


def test_trailer_shaped_line_in_body_is_rejected() -> None:
    msg = "docs: tidy\n\nSome text.\nSession-Link: https://example.com/abc\n"
    assert any("Session-Link" in p for p in problems(msg))


def test_urls_in_body_are_fine() -> None:
    msg = "docs: link\n\nSee https://example.com/path and http://example.org for details.\n"
    assert problems(msg) == []


def test_subject_length_and_empty() -> None:
    assert problems("") == ["subject line is empty"]
    assert problems("#comment only\n") == ["subject line is empty"]
    assert any("72" in p for p in problems("x" * 80))


def test_git_comment_lines_are_ignored() -> None:
    msg = "docs: tidy\n# Please enter the commit message\n# Co-authored-by: nobody\n"
    assert problems(msg) == []
