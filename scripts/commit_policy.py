#!/usr/bin/env python3
"""Commit-message policy for scrapewatch.

Rules (enforced by .githooks/commit-msg locally and by CI on every pushed commit):
1. Subject line: 1-72 characters, not blank.
2. Trailers (``Key: value`` lines in the final paragraph) are allowed only for ``Signed-off-by``.
3. No "Generated with" / "Generated by" footers anywhere, in any case.
4. No lines that look like a tool-authorship footer: a trailer-shaped line whose key is anything
   other than Signed-off-by, wherever it appears in the body.

Usage:
    commit_policy.py FILE            # check one message file (git hook)
    commit_policy.py --range A..B    # check every commit in a git range (CI)
    commit_policy.py --all           # check every commit reachable from HEAD (first push)
"""

from __future__ import annotations

import re
import subprocess
import sys

ALLOWED_TRAILERS = {"signed-off-by"}
TRAILER_RE = re.compile(r"^([A-Za-z][A-Za-z0-9-]*): \S.*$")
GENERATED_RE = re.compile(r"(?i)\bgenerated (with|by)\b")
MAX_SUBJECT = 72


def problems(message: str) -> list[str]:
    """Return the list of policy violations for one commit message (empty when it passes)."""
    lines = [ln.rstrip("\n") for ln in message.splitlines()]
    content = [ln for ln in lines if not ln.startswith("#")]
    while content and not content[0].strip():
        content.pop(0)
    out: list[str] = []
    if not content or not content[0].strip():
        return ["subject line is empty"]
    subject = content[0]
    if len(subject) > MAX_SUBJECT:
        out.append(f"subject line is {len(subject)} chars; max {MAX_SUBJECT}")
    for ln in content:
        if GENERATED_RE.search(ln):
            out.append(f"footer not allowed: {ln.strip()!r}")
        m = TRAILER_RE.match(ln.strip())
        if m and ln is not subject and m.group(1).lower() not in ALLOWED_TRAILERS:
            key = m.group(1)
            # URLs like "https: //" cannot match because of the \S after ": ".
            out.append(f"trailer not allowed: {key!r} (only Signed-off-by is permitted)")
    return out


def _git_messages(spec: list[str]) -> list[tuple[str, str]]:
    sep = "\x1e"
    fmt = f"--format=%H%x1f%B{sep}"
    raw = subprocess.run(  # noqa: S603 - fixed git command, args are refs
        ["git", "log", fmt, *spec],  # noqa: S607
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    items: list[tuple[str, str]] = []
    for chunk in raw.split(sep):
        if not chunk.strip():
            continue
        sha, _, body = chunk.lstrip("\n").partition("\x1f")
        items.append((sha.strip(), body))
    return items


def main(argv: list[str]) -> int:
    """CLI entry point; returns the exit code."""
    if not argv:
        print(__doc__)
        return 2
    if argv[0] in {"--range", "--all"}:
        spec = [argv[1]] if argv[0] == "--range" else ["HEAD"]
        failed = 0
        for sha, body in _git_messages(spec):
            probs = problems(body)
            if probs:
                failed += 1
                print(f"commit {sha[:12]} violates the commit-message policy:")
                for p in probs:
                    print(f"  - {p}")
        if failed:
            print(f"{failed} commit(s) failed. See scripts/commit_policy.py for the rules.")
            return 1
        print("commit-message policy: ok")
        return 0
    with open(argv[0], encoding="utf-8") as fh:
        probs = problems(fh.read())
    if probs:
        print("commit message rejected:")
        for p in probs:
            print(f"  - {p}")
        print("Allowed: a subject, a body, and only Signed-off-by trailers (git commit -s).")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
